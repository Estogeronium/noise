function make(r, kind, theme) {
  const sub = pick(r, SUBS);
  if (theme && r() < 0.8) {
    if (kind === "slogan") return { kind, text: pick(r, THEMED_SLOGANS)(theme), sub };
    return { kind: kind === "alert" ? "notice" : kind, text: pick(r, THEMED)(pick(r, ORGS), theme), sub };
  }
  switch (kind) {
    case "ticker":
      return { kind, text: `${pick(r, ORGS)} сообщает: ${pick(r, EVENTS)}.`, sub };
    case "notice":
      return { kind, text: `Гражданам напоминаем: ${pick(r, RULES)}.`, sub };
    case "alert": {
      const [a, b] = pick(r, ALERTS);
      return { kind, text: `ВНИМАНИЕ: ${a}. ${b[0].toUpperCase()}${b.slice(1)}.`, sub };
    }
    default: {
      const w = [pick(r, IMPERATIVES), pick(r, IMPERATIVES), pick(r, IMPERATIVES)];
      return { kind: "slogan", text: `${w[0]}. ${w[1]}. ${w[2]}.`, sub };
    }
  }
}

const KINDS = ["ticker", "slogan", "notice", "alert"];

export function localSignals(n, theme = "", rng = Math.random) {
  const out = [];
  for (let i = 0; i < n; i++) out.push(make(rng, pick(rng, KINDS), theme));
  return out;
}
